import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const output = new URL("../plugins/ultraclaude/skills/claude-workflow/scripts/schema-validator.mjs", import.meta.url);
const result = await build({
  absWorkingDir: fileURLToPath(new URL("../", import.meta.url)),
  entryPoints: ["tools/schema-source.mjs"], tsconfigRaw: {},
  bundle: true, write: false, platform: "node", format: "esm", target: "node18",
  minify: true, legalComments: "inline",
  banner: { js: "// Generated by tools/build-validator.mjs. Includes Ajv (MIT), fast-uri (BSD-3-Clause), and MIT dependencies; see THIRD_PARTY_NOTICES.md." },
});
const content = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) throw new Error("Bundled validator is stale; run npm run build.");
} else {
  await writeFile(output, content);
}
